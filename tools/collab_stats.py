#!/usr/bin/env python3
"""Collaboration stats for the demo (task 6). Standard library only.

Reads agents/*.md, comms/*.md, TASKS.md and git log, writes results/collab-stats.md.
Run from anywhere: python3 tools/collab_stats.py
"""
import re
import subprocess
from collections import Counter, defaultdict
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TYPES = ["hello", "request", "answer", "decision", "handoff", "status", "blocker"]


def company(tool):
    t = tool.lower()
    if "claude" in t or "anthropic" in t:
        return "Anthropic"
    if "codex" in t or "chatgpt" in t or "openai" in t or "gpt" in t:
        return "OpenAI"
    if "gemini" in t or "google" in t:
        return "Google"
    return tool.strip() or "unknown"


def field(text, name):
    m = re.search(r"^%s:\s*(.*)$" % name, text, re.M)
    return m.group(1).strip() if m else ""


def main():
    agents = {}
    for p in sorted((ROOT / "agents").glob("*.md")):
        if p.stem == "TEMPLATE" or p.stem.endswith("_notes"):
            continue
        txt = p.read_text(encoding="utf-8")
        agents[field(txt, "agent_id") or p.stem] = company(field(txt, "tool"))
    companies = sorted(set(agents.values()))

    per_agent, per_type = Counter(), Counter()
    matrix = defaultdict(Counter)
    reviews = Counter()  # (reviewer, owner) -> count
    stamps = []
    for p in sorted((ROOT / "comms").glob("*.md")):
        m = re.match(r"(\d{8}-\d{4})_([^_]+)_", p.name)
        if not m:
            continue
        sender = m.group(2)
        txt = p.read_text(encoding="utf-8")
        typ = field(txt, "type").split()[0].lower() if field(txt, "type") else "?"
        to = field(txt, "to").split()[0] if field(txt, "to") else "?"
        per_agent[sender] += 1
        per_type[typ] += 1
        matrix[sender][typ] += 1
        stamps.append(datetime.strptime(m.group(1), "%Y%m%d-%H%M"))
        if "review" in p.name and "applied" not in p.name and typ in ("answer", "handoff") and to not in ("all", "?"):
            reviews[(sender, to)] += 1

    # planned reviews from TASKS.md (Reviewer column -> Owner column)
    planned = []
    for line in (ROOT / "TASKS.md").read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 5 and cells[0].isdigit() and cells[2] and cells[3]:
            planned.append((cells[3], cells[2], cells[0]))

    log = subprocess.run(["git", "log", "--format=%s"], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout.splitlines()
    commits = Counter()
    for s in log:
        m = re.match(r"\[([^\]]+)\]", s)
        who = m.group(1) if m else "(none)"
        commits[who if who in agents else "non-agent"] += 1

    out = ["# Collaboration stats (task 6)", "",
           "Generated by `python3 tools/collab_stats.py` from `agents/`, `comms/`, `TASKS.md` and `git log`. Do not edit by hand.", ""]
    out += ["## Team", "", "* Agents: %d" % len(agents),
            "* Companies: %d (%s)" % (len(companies), ", ".join(companies)), ""]
    out += ["| Agent | Company |", "|---|---|"]
    out += ["| %s | %s |" % (a, c) for a, c in sorted(agents.items())]
    out += ["", "## Messages in comms/", "", "Total: %d" % sum(per_agent.values()), "",
            "| Agent | Messages | " + " | ".join(TYPES) + " |",
            "|---|---|" + "---|" * len(TYPES)]
    for a, n in per_agent.most_common():
        out.append("| %s | %d | %s |" % (a, n, " | ".join(str(matrix[a][t]) for t in TYPES)))
    out.append("| **all** | %d | %s |" % (sum(per_agent.values()), " | ".join(str(per_type[t]) for t in TYPES)))
    out += ["", "## Cross reviews", "", "Assigned in `TASKS.md` (reviewer -> owner, task):", ""]
    out += ["* %s -> %s (task %s)" % r for r in planned]
    cross = sum(1 for r, o, _ in planned if company(agents.get(r, "")) != company(agents.get(o, "")))
    out += ["", "Of these, %d of %d are cross-company." % (cross, len(planned)), "",
            "Review messages in `comms/` (file name contains `review` but not `applied`, type answer or handoff, addressed to one agent):", ""]
    out += ["* %s -> %s: %d" % (r, o, n) for (r, o), n in sorted(reviews.items())] or ["* none"]
    out += ["", "## Commits", "", "Total: %d" % sum(commits.values()), "", "| Author prefix | Commits |", "|---|---|"]
    out += ["| %s | %d |" % (a, n) for a, n in commits.most_common()]
    out += ["", "`non-agent` = commits whose message has no registered `[agent-id]` prefix (for example humans).", ""]
    if stamps:
        first, last = min(stamps), max(stamps)
        d = last - first
        out += ["## Time span", "",
                "First message: %s KST. Last message: %s KST." % (first.strftime("%Y-%m-%d %H:%M"), last.strftime("%Y-%m-%d %H:%M")),
                "Span: %d days %d hours." % (d.days, d.seconds // 3600), ""]
    (ROOT / "results" / "collab-stats.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote results/collab-stats.md")


if __name__ == "__main__":
    main()
